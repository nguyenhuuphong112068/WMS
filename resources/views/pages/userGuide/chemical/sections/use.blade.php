<p>Ghi nhận mỗi lần lấy hoá chất ra dùng. <b>Không cần đề nghị và ký duyệt</b>: lưu là trừ tồn ngay và ghi vào
    <a href="#so-su-dung">Sổ sử dụng</a>. Tab này còn chứa <b>Phiếu Tạm</b>, nơi gom các dòng đã chọn nhưng chưa ghi thật.</p>

<h3>Ghi phiếu sử dụng</h3>
<ol class="ug-steps">
    <li>Bấm <span class="btn btn-sm btn-primary ug-ui"><i class="fas fa-plus mr-1"></i> Sử dụng hoá chất</span>.</li>
    <li>Chọn lô bằng một trong hai cách:
        <ul>
            <li><b>Cách 1 · Quét mã xuất nhập</b>: đưa máy quét vào mã trên nhãn, hoặc gõ mã rồi Enter.</li>
            <li><b>Cách 2 · Tồn kho của phòng</b>: bấm <b>Chọn Từ Tồn Kho</b>, tick một hoặc nhiều lô còn tồn, còn hạn, rồi
                <b>Thêm Vào Danh Sách</b>.</li>
        </ul>
    </li>
    <li>Mỗi dòng nhập <b>Số Lượng Dùng</b> và <b>Mục đích</b> (gõ tìm tên sản phẩm hoặc gõ tự do). Hoá chất cấm phải chọn thêm
        <b>Người Kiểm Tra</b> là Quản Lý Kho Hoá Chất của phòng. Cột <b>Tồn Còn</b> báo ngay nếu vượt tồn.</li>
    <li>Bấm <span class="btn btn-sm btn-primary ug-ui"><i class="fas fa-save mr-1"></i> Lưu</span> để ghi thật vào sổ, hoặc
        <span class="btn btn-sm btn-outline-primary ug-ui"><i class="fas fa-clock mr-1"></i> Lưu Tạm</span> để giữ lại, chưa trừ kho.</li>
</ol>

<h3>Quy tắc chọn lô và số lượng</h3>
<ul>
    <li>Chỉ chọn được lô <b>còn hạn</b>, <b>còn tồn</b> và đã <b>kiểm tra Đạt</b>.</li>
    <li>Hoá chất có hạn dùng mặc định mà lô <b>chưa xác định hạn dùng nội bộ</b> thì chưa dùng được. Vào
        <a href="#han-dung">Tồn Kho › tab Chưa có hạn nội bộ</a> để xác định trước.</li>
    <li>Được dùng vượt tồn còn lại tối đa <b>5%</b> (bù sai số cân đong); lô nhận lẻ từ phòng khác thì không được vượt.</li>
    <li>Phần đang nằm trong Phiếu Tạm của <b>bất kỳ ai</b> cũng được tính là đang giữ. Form hiện tên người đang giữ để bạn liên hệ.</li>
</ul>

<h3>Phiếu Tạm</h3>
<p>Mỗi người có một phiếu tạm riêng, gồm mọi dòng mình đã Lưu Tạm. Có thể sửa số lượng, người kiểm tra, mục đích ngay trên bảng, rồi:</p>
<ul>
    <li><b>Lưu</b> trên từng dòng: ghi riêng dòng đó vào sổ.</li>
    <li><span class="btn btn-sm btn-primary ug-ui"><i class="fas fa-save mr-1"></i> Lưu Toàn Bộ</span>: ghi cả phiếu. Chỉ cần một dòng lỗi
        thì <b>không dòng nào được ghi</b>; sửa dòng lỗi rồi thử lại.</li>
    <li><span class="btn btn-sm btn-secondary ug-ui"><i class="fas fa-trash mr-1"></i> Xoá Cả Phiếu</span>: bỏ toàn bộ phiếu tạm.</li>
</ul>
