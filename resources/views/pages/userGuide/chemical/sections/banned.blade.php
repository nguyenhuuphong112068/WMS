    tra cứu và in, ghi giống một cuốn sổ giấy.</p>

<ul>
    <li>Mỗi dòng là <b>một lần nhập hoặc một lần xuất / sử dụng</b>, xếp theo thời gian tăng dần.</li>
    <li><b>Tồn Của Lô</b>: số dư cộng dồn của từng lô. <b>Tổng Tồn Các Lô</b>: số dư cộng dồn của cả hoá chất, gộp mọi lô.</li>
    <li>Lọc theo khoảng ngày: phần trước ngày bắt đầu được cộng thành <b>số dư đầu kỳ</b>, nên số dư luôn đúng.</li>
    <li>Chỉ tính phiếu còn hiệu lực; phiếu đã khoá coi như chưa xảy ra.</li>
</ul>

