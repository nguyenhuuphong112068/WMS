<h3>Mã xuất nhập</h3>
<p>Mỗi lô nhập được cấp một mã riêng dạng <span class="ug-key">C-07-7KPMR9J4WD</span> (C + mã phòng + chuỗi ngẫu nhiên), in thành mã
    QR trên nhãn. Khi sử dụng, chỉ cần quét mã này. Phiếu sử dụng dùng lại đúng mã của lô, không sinh mã mới.</p>

<h3>Phân loại theo Nghị định 24/2026</h3>
<p>Phân loại <b>không khai tay</b> ở danh mục mà hệ thống <b>tự suy</b> từ <b>Dữ Liệu Gốc › Hoạt Chất</b> và
    <b>Dữ Liệu Gốc › Hoá Chất</b>. Nhãn <span class="ug-chip"><i class="fas fa-shield-alt"></i> Kiểm soát đặc biệt</span> đánh dấu
    hoá chất thuộc Phụ lục III. Hoá chất thuộc <b>nhóm 11 - Hoá chất cấm (Luật Đầu tư 2025)</b> bắt buộc có người kiểm tra mỗi lần
    sử dụng và có <a href="#hoa-chat-cam">sổ theo dõi riêng</a>.</p>

<h3>Ba loại hạn dùng</h3>
<ul>
    <li><b>Hạn sử dụng</b> (hạn nhà sản xuất): ghi trên bao bì, nhập lúc nhập kho.</li>
    <li><b>Hạn dùng nội bộ</b>: tính từ ngày mở nắp + số tháng hạn dùng mặc định, không bao giờ dài hơn hạn nhà sản xuất.
        Hoá chất có hạn dùng mặc định thì <b>phải xác định hạn nội bộ trước khi dùng</b>.</li>
    <li><b>Hạn áp dụng</b>: hạn thực tế đang có hiệu lực, là hạn nội bộ nếu đã xác định, ngược lại là hạn nhà sản xuất.</li>
</ul>

<h3>Xuất vượt và âm kho</h3>
<p>Mỗi lần dùng được <b>vượt tồn còn lại tối đa 5%</b> để bù sai số cân đong. Phần vượt làm tồn bị <b>âm</b>, xử lý bằng
    <a href="#ton-kho">Cân đối</a>. Riêng lô nhận lẻ từ phòng khác thì không được vượt.</p>

<h3>Tương kỵ khi lưu trữ</h3>
<p>Dựa vào <b>Cảnh Báo An Toàn</b> (hình đồ GHS) khai ở danh mục, hệ thống chặn việc xếp hai hoá chất tương kỵ (ví dụ chất lỏng dễ
    cháy với chất oxy hoá) vào <b>cùng một tầng</b> của kệ/tủ. Hoá chất chưa khai cảnh báo an toàn thì không xét được.</p>

<h3>Ký điện tử bằng mật khẩu</h3>
<p>Các thao tác <span class="ug-chip is-warn">Ký bằng mật khẩu</span> (duyệt danh mục, xác nhận khai báo cổng quốc gia,
    quyết định loại bỏ, huỷ, ký dự trù) bắt buộc nhập lại mật khẩu đăng nhập (21 CFR Part 11).</p>

<h3>Sửa, duyệt, khoá ở Danh Mục không tải lại trang</h3>
<p class="mb-0">Ở Danh Mục Hoá Chất (tab Công Ty và Hoá Chất Của Phòng), <b>Sửa</b>, <b>Duyệt</b>, <b>Xác nhận khai báo
    cổng</b> và <b>Khoá / Mở khoá</b> lưu ngay tại chỗ: bảng tự cập nhật dòng vừa đổi, giữ nguyên tab, ô tìm kiếm, bộ lọc,
    trang đang xem và vị trí cuộn. Sai mật khẩu ký hoặc nhập sai thì hệ thống báo lỗi, trang vẫn giữ nguyên.
    <b>Thêm mới</b> vẫn tải lại trang.</p>
