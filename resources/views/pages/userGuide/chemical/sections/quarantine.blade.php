<p>Xử lý hoá chất <b>hỏng, hết hạn, biến chất</b> theo 3 bước. Từ bước 1 hàng đã bị trừ tồn nên không dùng hay chuyển đi được nữa.</p>

<ol class="ug-steps">
    <li><b>Cách ly</b>: mở <b>Tồn Kho Hoá Chất</b> (tab Theo mã xuất nhập hoặc Cận hạn dùng), bấm nút <b>Cách ly</b> trên lô, nhập
        <b>Số lượng cách ly</b>, chọn <b>Định khu Chờ Quyết Định</b> và ghi <b>Lý do cách ly</b>. Nút
        <span class="btn btn-sm btn-outline-danger ug-ui"><i class="fas fa-biohazard mr-1"></i> Cách ly từ Tồn Kho</span> ở tab này dẫn thẳng sang đó.</li>
    <li><b>Quyết định</b> (quyền <i>Quyết Định Loại Bỏ Hoá Chất Hỏng</i>), ghi căn cứ và nhập lại mật khẩu:
        <ul>
            <li><b>Loại bỏ</b>: hàng chuyển sang định khu <b>Loại Bỏ/Chờ Huỷ</b>, không thể quay lại kho.</li>
            <li><b>Trả về kho</b>: hoá chất đạt, tồn được cộng lại.</li>
        </ul>
    </li>
    <li><b>Huỷ</b>: khi đã tiêu huỷ thực tế, tick các phiếu chờ huỷ, bấm
        <span class="btn btn-sm btn-outline-danger ug-ui"><i class="fas fa-fire mr-1"></i> Huỷ mục đã chọn</span>, ghi phương pháp huỷ và nhập lại
        mật khẩu. Bước này không làm thay đổi tồn.</li>
</ol>
