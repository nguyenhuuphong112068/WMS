<p>Ghi nhận mỗi lần lấy chuẩn từ một ống ra dùng cho phép thử, hoặc loại bỏ ống. Lưu là trừ tồn ngay và ghi vào
    <b>Sổ sử dụng chất chuẩn</b>.</p>

<h3>Ghi phiếu sử dụng</h3>
<ol class="ug-steps">
    <li>Bấm <span class="btn btn-sm btn-primary ug-ui"><i class="fas fa-plus mr-1"></i> Sử dụng chất chuẩn</span>.</li>
    <li>Chọn <b>Loại Phiếu</b>: Sử dụng, hoặc Loại bỏ.</li>
    <li>Chọn <b>Tổ Sử Dụng</b> của bạn, rồi chọn ống trong danh sách ống <b>đã cấp cho tổ</b> (hiện người cấp, ngày cấp, số lô).</li>
    <li>Nhập <b>Số Lượng Xuất</b>, <b>Tên Sản Phẩm</b>, <b>Số Lô</b> sản phẩm và <b>Chỉ Tiêu</b>. Phiếu Loại bỏ thì ghi <b>Lý Do Loại Bỏ</b>
        (hết hạn, hỏng bao bì, tạp chất, OOS, BCSL...).</li>
    <li>Ống có kiểm soát khối lượng, ở lần dùng đầu: nhập <b>Khối Lượng Bì + Chuẩn</b> (cân trước khi dùng). Lưu.</li>
</ol>

