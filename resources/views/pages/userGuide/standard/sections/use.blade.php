<p>Ghi nhận mỗi lần lấy chuẩn từ một ống ra dùng cho phép thử. Lưu là trừ tồn ngay và ghi vào <b>Sổ sử dụng chất chuẩn</b>.
    Ống hỏng / hết hạn không ghi ở đây mà đi quy trình <a href="#cach-ly">Cách ly - Loại bỏ - Huỷ</a>.</p>

<h3>Ghi phiếu sử dụng</h3>
<ol class="ug-steps">
    <li>Bấm <span class="btn btn-sm btn-primary ug-ui"><i class="fas fa-plus mr-1"></i> Sử dụng chất chuẩn</span>.</li>
    <li><b>Loại Phiếu</b> luôn là Sử dụng.</li>
    <li>Chọn <b>Tổ Sử Dụng</b> của bạn, rồi chọn ống trong danh sách ống <b>đã cấp cho tổ</b> (hiện người cấp, ngày cấp, số lô).</li>
    <li>Nhập <b>Số Lượng Xuất</b>, <b>Tên Sản Phẩm</b>, <b>Số Lô</b> sản phẩm và <b>Chỉ Tiêu</b>.</li>
    <li>Ống có kiểm soát khối lượng, ở lần dùng đầu: nhập <b>Khối Lượng Bì + Chuẩn</b> (cân trước khi dùng). Lưu.</li>
</ol>

