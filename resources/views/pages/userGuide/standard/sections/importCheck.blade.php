<p>Các ống vừa nhập đang nằm trong khu Biệt Trữ chờ kiểm tra. Cách làm giống hoá chất và vật tư:</p>
<ol class="ug-steps">
    <li>Bấm <span class="btn btn-sm btn-success ug-ui"><i class="fas fa-clipboard-check mr-1"></i> Kiểm tra</span> trên ống.</li>
    <li><b>Đạt</b>: bắt buộc chọn <b>định khu vị trí lưu trữ thật</b>, bổ sung thông tin còn thiếu. Ống vào tồn và dùng được.</li>
    <li><b>Không đạt</b>: bắt buộc ghi kết luận. Ống coi như trả hàng, không bao giờ vào tồn.</li>
</ol>
