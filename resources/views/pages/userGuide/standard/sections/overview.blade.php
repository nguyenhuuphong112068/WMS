<p>
    Module <b>Chất Chuẩn</b> quản lý từng <b>ống chuẩn</b> dùng trong kiểm nghiệm, từ lúc nhập về cho tới khi dùng hết, huỷ, hoặc kết thúc
    đánh giá hạn dùng. Khác hoá chất, chuẩn được <b>cấp phát cho tổ</b> trước, rồi người trong tổ mới ghi sử dụng. Chuẩn còn có các loại hạn
    dùng riêng (retest, check online), kiểm soát khối lượng và đánh giá hạn dùng chuẩn thứ cấp.
</p>

