<p>Tồn <b>tính tự động</b> từ phiếu nhập, cân đối và phiếu sử dụng / loại bỏ. Chọn <b>Từ ngày - Đến ngày</b> (mặc định trọn tháng
    hiện tại) để xem Tồn Đầu Kỳ, Nhập, Sử Dụng, Huỷ trong kỳ và Tồn Cuối Kỳ.</p>

<ul>
    <li><b>Theo mã ống chuẩn</b>: từng ống, kèm hạn dùng, hạn nội bộ, vị trí, % đã dùng, nút Cân đối, xác định hạn nội bộ, file đính kèm.</li>
    <li><b>Theo chất chuẩn</b>: gộp các ống theo chất chuẩn.</li>
    <li><b>Theo định khu</b>: sơ đồ kho - kệ - vị trí đang chứa ống nào.</li>
</ul>

<h3>Cân đối</h3>
<p>Nhập <b>Số Lượng Cân Đối</b> là số điều chỉnh (+ hoặc −) để đưa tồn về đúng thực tế, ví dụ sau khi xuất vượt làm tồn âm.</p>
