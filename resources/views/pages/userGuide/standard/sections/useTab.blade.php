<p>Tab đầu tiên, mở mặc định khi vào màn Sử Dụng Chất Chuẩn. Tab liệt kê mọi ống chuẩn kho đã <a href="#de-nghi-noi-bo">cấp phát cho các Tổ</a> mà <b>chưa lập phiếu sử dụng</b>, cùng bố cục bảng
    chọn ống cấp cho tổ trước đây: mã ống (lô, định khu), chất chuẩn, tổ + mã phiếu đề nghị, qui cách, nhà sản xuất, mục đích, số lượng
    đề nghị / đã cấp (người cấp, thời điểm cấp), ĐVT, trả chuẩn, sản phẩm, chỉ tiêu, KNV, ghi chú. Số trên nút tab là số ống đang chờ sử dụng.
    Dòng có KNV là chính bạn hiện thêm nhãn <b>Bạn</b>.</p>

<h3>Ghi phiếu sử dụng</h3>
<ol class="ug-steps">
    <li>Lọc theo <b>Tổ</b> hoặc gõ tên chuẩn / mã ống / lô / KNV vào ô tìm kiếm để tìm ống cần dùng.</li>
    <li>Bấm <span class="btn btn-sm btn-primary ug-ui"><i class="fas fa-vial mr-1"></i> Sử dụng</span> trên dòng ống đó (cần quyền lập phiếu sử dụng).
        Form <b>Sử Dụng Chất Chuẩn</b> mở ra với <b>Tổ Sử Dụng</b>, <b>Phiếu Đề Nghị</b>, <b>KNV</b> và thông tin ống đã điền sẵn, không đổi được;
        <b>Tên Sản Phẩm</b> và <b>Chỉ Tiêu</b> lấy sẵn theo dòng đề nghị, sửa được.</li>
    <li>Nhập <b>Số Lượng Xuất</b> và <b>Số Lô</b> sản phẩm.</li>
    <li>Ống có kiểm soát khối lượng, ở lần dùng đầu: nhập <b>Khối Lượng Bì + Chuẩn</b> (cân trước khi dùng). Bấm
        <span class="btn btn-sm btn-primary ug-ui"><i class="fas fa-save mr-1"></i> Lưu</span>.</li>
</ol>

<p>Số lượng xuất khác số lượng đề nghị, hoặc vượt tồn còn lại của ống, thì hệ thống hỏi xác nhận trước khi lưu. Lưu xong tồn bị trừ ngay,
    phiếu vào <a href="#so-su-dung">Sổ sử dụng chất chuẩn</a>, ống rời khỏi tab này và trang quay lại tab <b>Sử dụng chuẩn</b> để dùng tiếp ống khác.
    Thẻ <span class="ug-key">Chuẩn đã cấp cho bạn</span> ở Trang chủ của KNV cũng tự hết.</p>

<p>Từ Trang chủ, KNV bấm thẻ <span class="ug-key">Chuẩn đã cấp cho bạn</span> (hoặc một dòng ống trong thẻ) là sang thẳng tab này; dòng ống
    vừa bấm được tô sáng xanh và cuộn tới giữa màn hình để bấm <b>Sử dụng</b> ngay.</p>

