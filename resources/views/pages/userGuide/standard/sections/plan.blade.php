<p>Xem <b>theo thời gian</b>: gom mọi mốc đánh giá của mọi phiếu còn hiệu lực trong phòng, xếp theo ngày đến hạn trong khoảng
    <b>từ ngày - đến ngày</b> đã chọn, để biết kỳ tới phải kiểm những ống nào.</p>
<ul>
    <li>Tình trạng từng mốc: <b>Đã đánh giá</b>, <b>Quá hạn</b>, <b>Sắp đến hạn</b>, <b>Chưa tới hạn</b>.</li>
    <li>Bấm vào một dòng để mở trang chi tiết phiếu bên <a href="#danh-gia">Chuẩn Thứ Cấp</a> và ghi kết quả.</li>
    <li>Đầu trang nhắc số ống chuẩn thứ cấp <b>còn tồn mà chưa lập phiếu</b>, để bạn lập bổ sung.</li>
</ul>
<p class="mb-0">Trang chỉ để xem, không ghi dữ liệu.</p>
