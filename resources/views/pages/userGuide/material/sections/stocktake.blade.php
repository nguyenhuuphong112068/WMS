<p>Đếm thực tế toàn bộ kho vật tư của phòng <b>mỗi quý một lần</b> (Q1: tháng 1-3, Q2: 4-6, Q3: 7-9, Q4: 10-12), rồi
    đưa tồn sổ sách về đúng số thực đếm. Kỳ kiểm kê là quý hiện tại, hệ thống tự xác định.</p>

<ol class="ug-steps">
    <li>Bấm <b>Mở Phiếu</b>. Hệ thống chụp lại <b>tồn sổ sách</b> của mọi mã xuất nhập còn số dư tại thời điểm mở.</li>
    <li>Đi đếm và nhập <b>Thực Tế Đếm</b> cho từng dòng. Quét mã QR trên nhãn lô (bằng máy quét hoặc camera) hoặc gõ mã rồi
        Enter để nhảy thẳng tới dòng cần đếm. Ghi chú lý do nếu lệch.</li>
    <li>Cột <b>Chênh Lệch</b> = số đếm − tồn sổ sách được tính ngay. Có thể lưu dần và đếm tiếp sau.</li>
    <li>Khi đã đếm <b>đủ mọi dòng</b>, bấm <b>Chốt Phiếu</b>.</li>
</ol>

<h3>Khi chốt phiếu</h3>
<ul>
    <li>Dòng lệch được tự ghi một lần <b>cân đối</b> đúng bằng phần lệch, kéo tồn sổ sách về số thực đếm.</li>
    <li>Vẫn áp dụng 2 giới hạn của Cân đối: tổng cân đối của lô không quá <b>5%</b> lượng nhập, và tồn không âm. Dòng vi phạm
        <b>không</b> tự cân đối mà được đánh dấu <b>Chờ Xử Lý</b> để làm rõ riêng.</li>
</ul>

