<p>Trả lời câu hỏi: <b>tồn hiện có của phòng có đủ cho nhu cầu theo chu kỳ của tháng tới không, thiếu bao nhiêu?</b>
    Mục đích là để kịp lập dự trù trước khi hết hàng.</p>

<div class="ug-callout">
    <i class="fas fa-calculator"></i>
    <div>
        <b>Khả dụng</b> = Tồn hiện hành − Đã đề nghị nhưng kho chưa cấp − Phần chu kỳ chưa tạo đề nghị từ nay tới hết tháng<br>
        <b>Thiếu / Đủ</b> = Khả dụng − Nhu cầu theo chu kỳ của tháng đang xét
    </div>
</div>

<ul>
    <li><b>Tồn hiện hành</b> không tính lô đã hết hạn.</li>
    <li><b>Nhu cầu</b> lấy từ các <a href="#danh-sach-chu-ky">danh sách theo chu kỳ</a> ăn vào kho của phòng: danh sách nội bộ của
        phòng, và danh sách liên phòng ban của phòng khác <b>gửi tới</b> phòng mình. Danh sách mình gửi đi xin phòng khác không tính.</li>
    <li>Cột <b>lượng nên dự trù</b> gợi ý số cần mua để đủ nhu cầu và vẫn giữ được ngưỡng tồn tối thiểu. Các dòng
        <b>Không đáp ứng</b> tự xuất hiện ở <a href="#can-du-tru">Danh sách vật tư cần dự trù</a>.</li>
    <li>Bấm vào số nhu cầu để xem danh sách chu kỳ nào tạo ra nó.</li>
</ul>

